def text(key: str) -> str:
    """Библия сериала одним текстом для агентов: мир, герои, форматы, словарь рендера, общие правила удержания и запреты."""
    s = S[key]
    cast = "\n".join(f"- {k} — {c['name']}: {c['who']}. Голос: {c['how']}." for k, c in s["cast"].items())
    fmts = "\n".join(f"- {k}: {v}" for k, v in s["formats"].items())
    vocab = (f"СЛОВАРЬ РЕНДЕРА (только это можно показать):\n- локации: {', '.join(s['sets'])}\n- действия: {', '.join(s['actions'])}\n"
             f"- эмоции: {', '.join(EMOTIONS)}\n- планы: {', '.join(s['shots'])}"
             + (f"\n- предметы/картинки: {', '.join(s['props'])}" if s["props"] else "")
             + ("\n- экран телевизора может показывать короткую надпись или картинку из списка" if s.get("tv") else ""))
    return (f"СЕРИАЛ «{s['title']}». Рисуется и рендерится нашей программой, поэтому всё видимое — только из словаря.\n\nМИР:\n{s['world']}\n\n"
            f"ГЕРОИ (ключ — имя):\n{cast}\n\nФОРМАТЫ:\n{fmts}\n\n{vocab}\n\n{bible.RETENTION}\n\n{bible.BANS}\n\n{bible.BPN}")
